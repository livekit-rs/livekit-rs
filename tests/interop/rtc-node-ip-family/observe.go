const apiKey = "ownednodeip"
const apiSecret = "fixture-secret-only-for-local-loopback-tests"

var (
	// allowedNodeIPText bounds the node_ip text that may reach a daemon argument or
	// YAML scalar: IPv4/IPv6 literals, comma pairs (including the spaces Go's
	// UnmarshalString trims at config.go:245), zone ids and the empty string. The
	// daemon is exec'd without a shell, so the bound is defence in depth against an
	// argument-splitting value rather than a quoting hazard.
	allowedNodeIPText = regexp.MustCompile(`^[0-9A-Za-z:.,%\- /]*$`)
	// explicitIPPattern reads the slot object Go/Rust log when a rewrite is
	// installed, i.e. the post-parse V4/V6 classification for `rtc.node_ip`
	// (`pkg/rtcconfig/webrtc_config.go:112`).
	explicitIPPattern = regexp.MustCompile(
		`using explicit node IP for NAT1To1Ips\s+\{"ip": (\{[^}]*\})`)
	advertisePattern = regexp.MustCompile(`"advertiseInternalIP": (true|false)`)
	nodeIPPattern    = regexp.MustCompile(`"nodeIP": "([^"]*)"`)
	nodeIDPattern    = regexp.MustCompile(`"nodeID": "([^"]*)"`)
)

func main() {
	binary := flag.String("binary", "", "absolute path to the immutable daemon")
	out := flag.String("output", "", "absolute fresh output directory")
	profile := flag.String("profile", "", "profile label")
	nodeIPValue := flag.String("node-ip-value", "", "raw text written as the YAML rtc.node_ip scalar")
	nodeIPFlag := flag.String("node-ip-flag", "", "generated dotted flag name, e.g. rtc.node_ip.ipv6")
	nodeIPFlagValue := flag.String("node-ip-flag-value", "", "value passed to --<node-ip-flag>")
	nodeIPMapping := flag.String("node-ip-mapping", "", "mapping-form node_ip as a JSON object string")
	useExternalIP := flag.Bool("use-external-ip", false, "rtc.use_external_ip")
	pinLoopback := flag.Bool("pin-loopback", true, "pin rtc.interfaces.includes to the "+
		"loopback interface; false admits every interface so the family-scoped rewrite of "+
		"physical candidates is observable")
	flag.Parse()
	if *binary == "" || *out == "" || *profile == "" {
		fmt.Fprintln(os.Stderr, "usage: observe --binary B --output DIR --profile P [--node-ip-value T | --node-ip-flag N --node-ip-flag-value V | --node-ip-mapping J] [--use-external-ip]")
		os.Exit(2)
	}
	record := map[string]any{"profile": *profile, "driven_items": []string{
		"YAML:rtc.node_ip", "generated_flags:--rtc.node_ip.ipv4",
		"generated_flags:--rtc.node_ip.ipv6",
	}}
	if err := os.MkdirAll(*out, 0700); err != nil {
		fatal(record, *out, err)
	}
	before, err := hashFile(*binary)
	if err != nil {
		fatal(record, *out, err)
	}
	record["binary_sha256_before"] = before
	runErr := runProfileWithPortRetry(*binary, *out, *profile, *nodeIPValue, *nodeIPFlag,
		*nodeIPFlagValue, *nodeIPMapping, *useExternalIP, *pinLoopback, record)
	after, hashErr := hashFile(*binary)
	record["binary_sha256_after"] = after
	if hashErr != nil {
		runErr = errors.Join(runErr, hashErr)
	}
	record["binary_unchanged"] = before == after
	if runErr != nil {
		record["error"] = runErr.Error()
	}
	writeResult(record, *out)
	if runErr != nil {
		os.Exit(1)
	}
}

func fatal(record map[string]any, out string, err error) {
	record["error"] = err.Error()
	writeResult(record, out)
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func writeResult(record map[string]any, out string) {
	data, err := json.MarshalIndent(record, "", "  ")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(filepath.Join(out, "result.json"), append(data, '\n'), 0600); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func hashFile(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(data)
	return fmt.Sprintf("%x", sum[:]), nil
}

// maxPortRetries bounds how many times a profile is relaunched after its daemon dies on a
// port this harness had just reserved for it.
const maxPortRetries = 3

// errPortConflict marks a daemon that exited because a reserved loopback port was claimed
// between Close() and its own bind. Without the marker the readiness loop sees an early exit
// and records the row as a clean refusal (`refused: true`, `whip_create_status: 0`,
// `server_exit: 1`), so a fence whose oracle is supposed to START reads as a behaviour
// divergence -- which is how the C100 lane B run lost `fence-flag-v4-nonip`.
var errPortConflict = errors.New("reserved loopback port was claimed before the daemon bound it")

// runProfileWithPortRetry relaunches a profile whose daemon lost the bind race. The retry is
// recorded in the receipt rather than swallowed: a collision the harness absorbed is still a
// fact about this run, and the next reader has to be able to tell a recovered transient from a
// clean launch. Retries exhausted returns the error, so the lane stops loudly instead of
// filing an infrastructure collision as a parity finding.
func runProfileWithPortRetry(binary, out, profile, value, ipFlag, ipFlagValue, mapping string,
	useExternalIP, pinLoopback bool, record map[string]any) error {
	err := runProfile(binary, out, profile, value, ipFlag, ipFlagValue, mapping,
		useExternalIP, pinLoopback, record)
	for attempt := 1; errors.Is(err, errPortConflict) && attempt <= maxPortRetries; attempt++ {
		dir := filepath.Join(out, fmt.Sprintf("port-retry-%d", attempt))
		if mkErr := os.MkdirAll(dir, 0700); mkErr != nil {
			return errors.Join(err, mkErr)
		}
		record["port_conflict_retries"] = attempt
		record["port_conflict_error"] = err.Error()
		err = runProfile(binary, dir, profile, value, ipFlag, ipFlagValue, mapping,
			useExternalIP, pinLoopback, record)
		if err == nil {
			err = promoteLogs(dir, out)
		}
	}
	return err
}

// promoteLogs copies the winning attempt's daemon streams over the canonical names the
// harness reads, so a retried profile is laid out like any other while the losing attempts
// stay under port-retry-N/.
func promoteLogs(from, to string) error {
	var err error
	for _, name := range []string{"server.log", "server.stdout"} {
		data, readErr := os.ReadFile(filepath.Join(from, name))
		if readErr != nil {
			err = errors.Join(err, readErr)
			continue
		}
		err = errors.Join(err, os.WriteFile(filepath.Join(to, name), data, 0600))
	}
	return err
}

// reservePort binds an explicit loopback port BELOW the OS ephemeral band instead of asking
// the allocator for one. `net.Listen(":0")` returns 49152-65535 here (the measured
// `net.inet.ip.portrange.first` is 49152) -- the same pool the kernel draws on for an
// outbound socket's source port, and this profile opens a fresh client socket every 20 ms
// while it waits for readiness. A reserved number in that band is therefore only free until
// the next allocation takes it, which is what produced
// `listen tcp :50975: bind: address already in use` in the C100 lane B run.
func reservePort() (net.Listener, error) {
	base := 41000 + (os.Getpid()%150)*4
	for offset := 0; offset < 600; offset++ {
		listener, err := net.Listen("tcp4", fmt.Sprintf("127.0.0.1:%d", base+offset))
		if err == nil {
			return listener, nil
		}
	}
	return net.Listen("tcp4", "127.0.0.1:0")
}

// loopbackName resolves the UP loopback interface against the live OS table so the
// interface pin is host-independent (lo0 on macOS, lo on Linux). Only names are
// recorded, never machine addresses.
func loopbackName(record map[string]any) (string, error) {
	ifaces, err := net.Interfaces()
	if err != nil {
		return "", err
	}
	var table []map[string]any
	name := ""
	for _, iface := range ifaces {
		up := iface.Flags&net.FlagUp != 0
		lb := iface.Flags&net.FlagLoopback != 0
		table = append(table, map[string]any{"name": iface.Name, "up": up, "loopback": lb})
		if lb && up && name == "" {
			name = iface.Name
		}
	}
	record["enumerated_interfaces"] = table
	record["loopback_name"] = name
	if name == "" {
		return "", fmt.Errorf("no UP loopback interface found")
	}
	return name, nil
}

func runProfile(binary, out, profile, value, ipFlag, ipFlagValue, mapping string,
	useExternalIP, pinLoopback bool, record map[string]any) (err error) {
	loopback, err := loopbackName(record)
	if err != nil {
		return err
	}
	if value != "" && !allowedNodeIPText.MatchString(value) {
		return fmt.Errorf("refusing node_ip text with disallowed characters")
	}
	if ipFlag != "" && (strings.ContainsAny(ipFlag, " \t\n\"'") ||
		strings.ContainsAny(ipFlagValue, " \t\n\"'")) {
		return fmt.Errorf("refusing generated-flag arguments with shell metacharacters")
	}
	if ipFlag != "" && !allowedNodeIPText.MatchString(ipFlagValue) {
		return fmt.Errorf("refusing node_ip flag value with disallowed characters")
	}
	// Reserve exclusive loopback ports, then release them for the daemon to bind.
	listener, err := reservePort()
	if err != nil {
		return err
	}
	defer listener.Close()
	media, err := reservePort()
	if err != nil {
		listener.Close()
		return err
	}
	defer media.Close()
	address := listener.Addr().String()
	mediaAddress := media.Addr().String()

	rtc := map[string]any{
		"enable_loopback_candidate": true,
		"use_external_ip":           useExternalIP,
		"tcp_port":                  media.Addr().(*net.TCPAddr).Port,
		"port_range_start":          50000,
		"port_range_end":            60000,
	}
	if pinLoopback {
		// Pinning keeps the loopback candidate the ONLY admitted base, so any
		// candidate text that differs from 127.0.0.1 can only come from the rewrite.
		rtc["interfaces"] = map[string]any{"includes": []string{loopback}}
	} else {
		// No filter: the daemon gathers its real interface surface (loopback still
		// admitted because rtc.enable_loopback_candidate is true, the C31 consumer).
	}
	record["interfaces_pinned"] = pinLoopback
	if mapping != "" {
		var node map[string]any
		if err := json.Unmarshal([]byte(mapping), &node); err != nil {
			return fmt.Errorf("mapping form must be a JSON object: %w", err)
		}
		for key, val := range node {
			text, ok := val.(string)
			if (key != "ipv4" && key != "ipv6") || !ok ||
				(text != "" && !allowedNodeIPText.MatchString(text)) {
				return fmt.Errorf("mapping form key %q is not an ipv4/ipv6 address string", key)
			}
		}
		rtc["node_ip"] = node
	} else if value != "" {
		rtc["node_ip"] = value
	}
	if ipFlag != "" {
		// The generated dotted flag is a process argument, not YAML: it writes the
		// raw text into the named leaf after YAML/UnmarshalString would have run.
		rtc["node_ip"] = ""
	}
	config := map[string]any{
		"port":           listener.Addr().(*net.TCPAddr).Port,
		"bind_addresses": []string{"127.0.0.1"},
		"keys":           map[string]string{apiKey: apiSecret},
		"rtc":            rtc,
		"logging":        map[string]any{"level": "info"},
	}
	cfg, err := json.MarshalIndent(config, "", "  ")
	if err != nil {
		return err
	}
	cfgPath := filepath.Join(out, "server.yaml")
	if err = os.WriteFile(cfgPath, cfg, 0600); err != nil {
		return err
	}
	record["config_sha256"] = fmt.Sprintf("%x", sha256.Sum256(cfg))
	record["config_yaml"] = string(cfg)
	record["node_ip_channel"] = map[string]any{"yaml_scalar": value,
		"generated_flag": ipFlag, "generated_flag_value": ipFlagValue,
		"mapping_form": mapping}

	// Zap structured logs go to stderr (references/protocol-stable/logger/logger.go:195)
	// while a fatal startup error is printed with fmt.Println on stdout
	// (cmd/server/main.go:190-192), so the streams stay apart: merging them would hide
	// which channel carries the refusal text.
	logPath := filepath.Join(out, "server.log")
	stdoutPath := filepath.Join(out, "server.stdout")
	file, err := os.OpenFile(logPath, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	defer file.Close()
	stdoutFile, err := os.OpenFile(stdoutPath, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	defer stdoutFile.Close()
	args := []string{"--config", cfgPath}
	if ipFlag != "" {
		args = append(args, "--"+ipFlag, ipFlagValue)
	}
	command := exec.Command(binary, args...)
	command.Stdout, command.Stderr = stdoutFile, file
	for _, varEntry := range os.Environ() {
		if strings.HasPrefix(varEntry, "OTEL_") || strings.HasPrefix(varEntry, "SSL_CERT_") ||
			strings.HasPrefix(varEntry, "LIVEKIT_") || strings.HasPrefix(varEntry, "NODE_IP") ||
			strings.HasPrefix(varEntry, "UDP_PORT") {
			continue
		}
		command.Env = append(command.Env, varEntry)
	}
	if err = errors.Join(listener.Close(), media.Close()); err != nil {
		return err
	}
	if err = command.Start(); err != nil {
		return err
	}
	exited := make(chan error, 1)
	go func() { exited <- command.Wait() }()
	early := false
	defer func() {
		if !early {
			// Upstream quirk (carried from config-wiring-startup): the official
			// daemon accepts the first SIGTERM before `Start()` sets `running`, so
			// `Stop()` returns at `!running.Swap(false)` without releasing the
			// start path and a second SIGTERM is what actually exits. Escalating
			// here keeps a blocked-but-otherwise-healthy daemon comparable instead
			// of reporting a harness-side shutdown timeout.
			started := time.Now()
			second, killed := false, false
			_ = command.Process.Signal(syscall.SIGTERM)
			select {
			case <-exited:
			case <-time.After(6 * time.Second):
				second = true
				_ = command.Process.Signal(syscall.SIGTERM)
				select {
				case <-exited:
				case <-time.After(6 * time.Second):
					killed = true
					_ = command.Process.Kill()
					<-exited
				}
			}
			record["sigterm_to_exit_s"] = int(time.Since(started) / time.Millisecond)
			record["second_sigterm_sent"] = second
			record["sigkill_required"] = killed
		}
		if command.ProcessState != nil {
			record["server_exit"] = command.ProcessState.ExitCode()
		}
		var bindErr error
		for _, addr := range []string{address, mediaAddress} {
			rebound, e := net.Listen("tcp4", addr)
			if e == nil {
				e = rebound.Close()
			}
			bindErr = errors.Join(bindErr, e)
		}
		record["server_ports_released"] = bindErr == nil
		if data, e := os.ReadFile(stdoutPath); e == nil {
			record["daemon_stdout"] = string(data)
		}
		if data, e := os.ReadFile(logPath); e == nil {
			text := string(data)
			record["server_log"] = text
			record["readiness_line_found"] = strings.Contains(text, "starting LiveKit server")
			record["ip_not_set_refusal"] = strings.Contains(text,
				"ip address is required and not set")
			// The rewrite-installation line is the family-slot observable: it is
			// emitted only when the node IP was NOT auto-generated
			// (webrtc_config.go:91-116) and carries the post-parse slot text.
			record["explicit_node_ip_log"] = strings.Contains(text,
				"using explicit node IP for NAT1To1Ips")
			if m := explicitIPPattern.FindStringSubmatch(text); m != nil {
				record["node_ip_slots"] = m[1]
			}
			if m := advertisePattern.FindStringSubmatch(text); m != nil {
				record["advertise_internal_ip"] = m[1]
			}
			if idx := strings.Index(text, "starting LiveKit server"); idx >= 0 {
				line := text[idx:]
				if end := strings.Index(line, "\n"); end > 0 {
					line = line[:end]
				}
				record["readiness_line"] = line
				if m := nodeIPPattern.FindStringSubmatch(line); m != nil {
					record["node_ip_primary"] = m[1]
				}
				if m := nodeIDPattern.FindStringSubmatch(line); m != nil {
					record["node_id"] = m[1]
				}
			}
		}
		err = errors.Join(err, bindErr)
	}()

	base := "http://" + address
	client := &http.Client{Timeout: 4 * time.Second, Transport: &http.Transport{DisableKeepAlives: true}}
	// The WHIP create runs the daemon's whole gather/bind path, so it gets a
	// deliberately generous timeout: a stall must be recorded as a stall
	// (`whip_stalled`), not silently absorbed as a transport error.
	whipClient := &http.Client{Timeout: 30 * time.Second, Transport: &http.Transport{DisableKeepAlives: true}}
	until := time.Now().Add(12 * time.Second)
	ready := false
	for {
		select {
		case e := <-exited:
			early = true
			// A daemon that died holding a port we just released is the harness's own
			// collision, not a refusal: checked here, before the refusal defaults are
			// written, so the row can be relaunched instead of recorded.
			if data, readErr := os.ReadFile(stdoutPath); readErr == nil &&
				strings.Contains(string(data), "bind: address already in use") {
				return fmt.Errorf("%w: %s", errPortConflict, strings.TrimSpace(string(data)))
			}
			record["refused"] = true
			record["whip_create_status"] = 0
			record["whip_delete_status"] = 0
			record["host_candidate_ips"] = []string{}
			record["host_candidate_count"] = 0
			record["v4_advertised"] = []string{}
			record["v6_advertised"] = []string{}
			record["answer_sdp"] = ""
			record["early_exit"] = fmt.Sprintf("%v", e)
			return nil
		default:
		}
		response, e := client.Get(base + "/")
		if e == nil {
			response.Body.Close()
			if response.StatusCode == http.StatusOK {
				ready = true
				break
			}
		}
		if time.Now().After(until) {
			return fmt.Errorf("daemon readiness timeout")
		}
		time.Sleep(20 * time.Millisecond)
	}
	record["refused"] = false
	if !ready {
		return fmt.Errorf("daemon never became ready")
	}
	whipErr := exerciseWHIP(whipClient, base, record)
	time.Sleep(1 * time.Second)
	return whipErr
}

func exerciseWHIP(client *http.Client, url string, record map[string]any) (err error) {
	token, err := auth.NewAccessToken(apiKey, apiSecret).
		SetIdentity("owned-node-ip-publisher").
		SetVideoGrant(&auth.VideoGrant{RoomJoin: true, Room: "owned-node-ip-room"}).
		ToJWT()
	if err != nil {
		return err
	}
	pc, err := webrtc.NewPeerConnection(webrtc.Configuration{})
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, pc.Close()) }()
	if _, err := pc.AddTransceiverFromKind(webrtc.RTPCodecTypeAudio,
		webrtc.RTPTransceiverInit{Direction: webrtc.RTPTransceiverDirectionSendonly}); err != nil {
		return err
	}
	offer, err := pc.CreateOffer(nil)
	if err != nil {
		return err
	}
	gathered := webrtc.GatheringCompletePromise(pc)
	if err = pc.SetLocalDescription(offer); err != nil {
		return err
	}
	select {
	case <-gathered:
	case <-time.After(3 * time.Second):
		return fmt.Errorf("owned ICE gather timeout")
	}
	request, err := http.NewRequest("POST", url+"/whip/v1", strings.NewReader(pc.LocalDescription().SDP))
	if err != nil {
		return err
	}
	request.Header.Set("Content-Type", "application/sdp")
	request.Header.Set("Authorization", "Bearer "+token)
	response, err := client.Do(request)
	if err != nil {
		// A stall here is the observation, not a harness accident: the daemon was
		// ready but never answered the WHIP create within the client timeout.
		record["whip_stalled"] = true
		record["whip_create_status"] = 0
		record["host_candidate_ips"] = []string{}
		record["host_candidate_count"] = 0
		record["v4_advertised"] = []string{}
		record["v6_advertised"] = []string{}
		record["candidate_lines"] = []string{}
		record["answer_sdp"] = ""
		return err
	}
	body, readErr := io.ReadAll(response.Body)
	if err = errors.Join(readErr, response.Body.Close()); err != nil {
		return err
	}
	record["whip_create_status"] = response.StatusCode
	record["whip_stalled"] = false
	answer := string(body)
	record["answer_sdp"] = answer
	ips, v4, v6, lines := hostCandidates(answer)
	record["host_candidate_ips"] = ips
	record["host_candidate_count"] = len(ips)
	record["v4_advertised"] = v4
	record["v6_advertised"] = v6
	record["candidate_lines"] = lines
	location := response.Header.Get("Location")
	if response.StatusCode != http.StatusCreated || !strings.HasPrefix(location, "/whip/v1/") {
		record["whip_delete_status"] = 0
		return nil
	}
	defer func() {
		request, e := http.NewRequest("DELETE", url+location, nil)
		if e != nil {
			err = errors.Join(err, e)
			return
		}
		request.Header.Set("Authorization", "Bearer "+token)
		response, e := client.Do(request)
		if e != nil {
			err = errors.Join(err, e)
			return
		}
		record["whip_delete_status"] = response.StatusCode
		err = errors.Join(err, response.Body.Close())
	}()
	if err := pc.SetRemoteDescription(webrtc.SessionDescription{
		Type: webrtc.SDPTypeAnswer, SDP: answer}); err != nil {
		return err
	}
	return nil
}

// hostCandidates returns the sorted unique HOST candidate addresses, split by
// address family, plus the verbatim candidate lines. The SDP candidate grammar is
// `a=candidate:<foundation> <component> <transport> <priority> <addr> <port> typ <type>`,
// so field 4 is the advertised address the rewrite rule produces.
func hostCandidates(sdp string) (ips []string, v4 []string, v6 []string, lines []string) {
	seen := map[string]bool{}
	for _, line := range strings.Split(sdp, "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "a=candidate:") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 7 {
			continue
		}
		typ := ""
		for i := 0; i+1 < len(fields); i++ {
			if fields[i] == "typ" {
				typ = fields[i+1]
				break
			}
		}
		if typ != "host" {
			continue
		}
		addr := fields[4]
		lines = append(lines, line)
		if seen[addr] {
			continue
		}
		seen[addr] = true
		ips = append(ips, addr)
		if ip := net.ParseIP(strings.TrimSuffix(strings.Split(addr, "%")[0], "]")); ip != nil {
			if ip.To4() != nil {
				v4 = append(v4, addr)
			} else {
				v6 = append(v6, addr)
			}
		}
	}
	for _, list := range []*[]string{&ips, &v4, &v6} {
		sort.Strings(*list)
		if *list == nil {
			*list = []string{}
		}
	}
	return ips, v4, v6, lines
}
