// SPEC-0077 C99 — launched-MAIN rtc.node_ip family/candidate observer.
//
// Run from the fixed Go module (references/livekit-stable) with either immutable
// daemon (locked Go oracle e5655ac or the Rust livecloud release candidate). It
// launches ONE daemon whose ONLY varied surface is the `rtc.node_ip` value and the
// channel it arrives through, then drives an authenticated WHIP Create/DELETE with a
// Pion offer that configures no interface filter and no rewrite of its own, and
// records what the daemon actually advertised.
//
// Observables (all of them produced by the daemon, not by this driver):
//
//	a. HOST ICE candidate IPs in the SDP answer — the mediatransportutil catch-all
//	   NAT1To1 rewrite (`pkg/rtcconfig/webrtc_config.go:91-116`,
//	   `SetNAT1To1AddressRewriteRules` -> livekit-ice `external_ip_mapper.go:90-127`
//	   `addExternalMappings`, which keys the sole external IP by ITS OWN family, and
//	   `:252-341` `newAddressRewriteMapper`), plus the Rust mirror
//	   `crates/livecloud/src/interfaces.rs:129-141`.
//	b. the `nodeIP` field of the `starting LiveKit server` readiness line
//	   (`pkg/service/server.go:281,309`), i.e. `NodeIP.PrimaryIP()` over the RAW
//	   config strings (`pkg/rtcconfig/config.go:280-285`) — the text a client of the
//	   cluster sees for this node.
//	c. startup integrity: exit code, HTTP readiness, WHIP 201/200, port release,
//	   and the `ip address is required and not set` refusal if the node identity
//	   never resolves (`pkg/routing/node.go:53-55`).
//
// The node_ip text arrives through three distinct upstream channels, which is the
// point of the matrix:
//
//	--node-ip-value      YAML `rtc.node_ip: "<text>"`  -> NodeIP.UnmarshalString
//	                     (config.go:235-263), which classifies with `ip.To4() != nil`
//	                     (:249) and stores `ip.String()`, so "::ffff:a.b.c.d" lands in
//	                     the IPv4 slot ALREADY normalised to "a.b.c.d".
//	--node-ip-flag <name> generated dotted flag (e.g. rtc.node_ip.ipv6) writing the RAW
//	                     text straight into the struct leaf
//	                     (`pkg/config/config.go:96-115`), bypassing UnmarshalString, so
//	                     an IPv4-mapped literal stays raw and sits in the named slot.
//	--node-ip-mapping    YAML `rtc.node_ip: {ipv4: ..., ipv6: ...}` — go-yaml calls the
//	                     custom Unmarshaler for a mapping node with `value.Value == ""`,
//	                     so UnmarshalString returns at its empty-string guard
//	                     (config.go:236-238) and the mapping is IGNORED upstream; the
//	                     node IP then comes from `Validate`'s discovery
//	                     (config.go:108-132) with NodeIPAutoGenerated = true, which is
//	                     precisely the condition that SUPPRESSES the rewrite at
//	                     webrtc_config.go:91.
