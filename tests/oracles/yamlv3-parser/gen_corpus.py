# ------------------------------------------------- systematic truncations
bases = [
    ("trunc-a", "%TAG !e! tag:e.com:\n--- !e!m\na: [1, \"two\", 'three']\nb: {c: &x d, e: *x}\n# c\n- x\n"),
    ("trunc-b", "k: |-\n  lit\n  eral\nf: >\n  fol\n  ded\ns: - 1\n"),
    ("trunc-c", "- a # c\n- ? k\n  : v\n- \"e\\u00e9\\\n  x\"\n...\n"),
]
for name, text in bases:
    data = text.encode("utf-8")
    for i in range(0, len(data) + 1, 2):
        add("%s-%03d" % (name, i), data[:i])

# ---------------------------------------- every single-character mutation
mut_base = "a: [b, {c: d}]\n"
for i, ch in enumerate(mut_base):
    for rep in ["-", "?", ":", "#", "&", "*", "!", "|", ">", "'", '"', "%", "@", "\t", " ", "\n"]:
        if rep == ch:
            continue
        mutated = mut_base[:i] + rep + mut_base[i + 1:]
        add("mut-%02d-%02x" % (i, ord(rep)), mutated)

