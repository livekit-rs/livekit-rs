// Source observer only: no precomputed acceptance, candidates or expected flags.
package main

import (
 "encoding/json"
 "fmt"
 "net"
 "os"
 "sort"
 "sync"
 "time"

 rtcconfig "github.com/livekit/mediatransportutil/pkg/rtcconfig"
 ice "github.com/pion/ice/v4"
 webrtc "github.com/pion/webrtc/v4"
)

type muxObserver struct {
 ice.UDPMux
 mu sync.Mutex
 calls []string
}
func(m *muxObserver)GetConn(u string,a net.Addr)(net.PacketConn,error){
 m.mu.Lock();m.calls=append(m.calls,a.String());m.mu.Unlock()
 return m.UDPMux.GetConn(u,a)
}
func(m *muxObserver)observed()[]string{m.mu.Lock();defer m.mu.Unlock();return append([]string{},m.calls...)}
func ephemeral()int{p,e:=net.ListenUDP("udp4",&net.UDPAddr{IP:net.IPv4(127,0,0,1)});if e!=nil{panic(e)};port:=p.LocalAddr().(*net.UDPAddr).Port;if e=p.Close();e!=nil{panic(e)};return port}
func main(){
 enc:=json.NewEncoder(os.Stdout)
 devices,e:=net.Interfaces();if e!=nil{panic(e)};lo:=""
 for _,d:=range devices{if d.Flags&net.FlagUp!=0&&d.Flags&net.FlagLoopback!=0{lo=d.Name;break}}
 if lo==""{panic("actual UP loopback is required")}
 for _,dev:=range []bool{false,true}{for _,flag:=range []bool{false,true}{for _,onlyLoopback:=range []bool{false,true}{
  run(enc,dev,flag,onlyLoopback,lo)
 }}}
}
func run(enc *json.Encoder,dev,flag,onlyLoopback bool,lo string){
 row:=map[string]any{"id":fmt.Sprintf("dev-%t-explicit-loopback-%t-only-loopback-interface-%t",dev,flag,onlyLoopback),"development":dev,"requested_loopback":flag,"only_loopback_interface":onlyLoopback}
 // Explicit NodeIP avoids discovery and external STUN. This is a real Host
 // alias rewrite, not a requirement that public address equal physical base.
 cfg:=rtcconfig.RTCConfig{NodeIP:rtcconfig.NodeIP{V4:"127.0.0.1"},UseExternalIP:false,UseICELite:true,EnableLoopbackCandidate:flag,UDPPort:rtcconfig.PortRange{Start:ephemeral()}}
 if onlyLoopback{cfg.Interfaces.Includes=[]string{lo}}
 if e:=cfg.Validate(dev);e!=nil{row["validate_error"]=e.Error();emit(enc,row);return}
 row["validated_loopback"]=cfg.EnableLoopbackCandidate;row["node_ip_auto_generated"]=cfg.NodeIPAutoGenerated;row["node_ip_v4"]=cfg.NodeIP.V4
 wc,e:=rtcconfig.NewWebRTCConfig(&cfg,dev)
 if e!=nil{row["config_error"]=e.Error();emit(enc,row);return}
 if wc.UDPMux!=nil{defer wc.UDPMux.Close()}
 if wc.TCPMuxListener!=nil{defer wc.TCPMuxListener.Close()}
 row["nat1to1_ips"]=wc.NAT1To1IPs
 bases:=[]string{};var observed *muxObserver
 if wc.UDPMux!=nil{
  for _,a:=range wc.UDPMux.GetListenAddresses(){bases=append(bases,a.String())}
  observed=&muxObserver{UDPMux:wc.UDPMux};wc.SettingEngine.SetICEUDPMux(observed)
 }
 sort.Strings(bases);row["actual_bound_addresses"]=bases
 pc,e:=webrtc.NewAPI(webrtc.WithSettingEngine(wc.SettingEngine)).NewPeerConnection(wc.Configuration)
 if e!=nil{row["peer_error"]=e.Error();emit(enc,row);return};defer pc.Close()
 if _,e=pc.CreateDataChannel("source-loopback-observer",nil);e!=nil{row["channel_error"]=e.Error();emit(enc,row);return}
 var candidateMu sync.Mutex;candidateStrings:=[]string{}
 pc.OnICECandidate(func(c *webrtc.ICECandidate){if c!=nil{candidateMu.Lock();candidateStrings=append(candidateStrings,c.ToJSON().Candidate);candidateMu.Unlock()}})
 completed:=webrtc.GatheringCompletePromise(pc)
 offer,e:=pc.CreateOffer(nil);if e!=nil{row["offer_error"]=e.Error();emit(enc,row);return}
 if e=pc.SetLocalDescription(offer);e!=nil{row["set_local_error"]=e.Error();emit(enc,row);return}
 select{case <-completed:row["gather_complete"]=true;case <-time.After(5*time.Second):row["gather_complete"]=false}
 // Candidates come from the actual public callback, not inferred from mux
 // addresses or reconstructed from authored expectations.
 candidateMu.Lock();row["candidates"]=append([]string{},candidateStrings...);candidateMu.Unlock()
 if observed!=nil{row["registered_bases"]=observed.observed()}
 emit(enc,row)
}
func emit(enc *json.Encoder,row map[string]any){if e:=enc.Encode(row);e!=nil{panic(e)}}
